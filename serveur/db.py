"""Base PostgreSQL du serveur. Adresse dans DATABASE_URL (Neon, Supabase, Render…) ; le schéma est créé au
démarrage. Sans DATABASE_URL, en développement : un Postgres local lancé par pgserver (requirements-dev)."""
import os

from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from serveur import config

SCHEMA = """
CREATE TABLE IF NOT EXISTS utilisateurs(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL, nom TEXT UNIQUE NOT NULL,
  mdp TEXT NOT NULL, bio TEXT DEFAULT '', sport TEXT DEFAULT 'course', preferences TEXT DEFAULT '{}',
  visibilite_profil TEXT DEFAULT 'public', visibilite_activites TEXT DEFAULT 'abonnes',
  masquer_depart INTEGER DEFAULT 1, cree DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(jeton TEXT PRIMARY KEY, utilisateur INTEGER NOT NULL,
  expire DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS reinits(jeton TEXT PRIMARY KEY, utilisateur INTEGER NOT NULL,
  expire DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS itineraires(
  id TEXT PRIMARY KEY, utilisateur INTEGER NOT NULL, nom TEXT NOT NULL, sport TEXT NOT NULL,
  distance DOUBLE PRECISION NOT NULL, montee DOUBLE PRECISION, coords TEXT NOT NULL, ele TEXT, resume TEXT,
  favori INTEGER DEFAULT 0, partage INTEGER DEFAULT 0, cree DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS activites(
  id TEXT PRIMARY KEY, utilisateur INTEGER NOT NULL, id_client TEXT NOT NULL, nom TEXT NOT NULL,
  sport TEXT NOT NULL, debut DOUBLE PRECISION NOT NULL, duree DOUBLE PRECISION, duree_totale DOUBLE PRECISION,
  distance DOUBLE PRECISION NOT NULL, denivele DOUBLE PRECISION, splits TEXT, segments TEXT NOT NULL,
  itineraire TEXT, visibilite TEXT NOT NULL, strava_upload TEXT, strava_statut TEXT, strava_erreur TEXT,
  strava_activite TEXT, cree DOUBLE PRECISION NOT NULL, description TEXT DEFAULT '', ressenti TEXT,
  UNIQUE(utilisateur, id_client));
CREATE INDEX IF NOT EXISTS activites_par_date ON activites(utilisateur, debut);
CREATE TABLE IF NOT EXISTS abonnements(suiveur INTEGER NOT NULL, suivi INTEGER NOT NULL,
  cree DOUBLE PRECISION NOT NULL, PRIMARY KEY(suiveur, suivi));
CREATE TABLE IF NOT EXISTS jaimes(utilisateur INTEGER NOT NULL, activite TEXT NOT NULL,
  PRIMARY KEY(utilisateur, activite));
CREATE TABLE IF NOT EXISTS commentaires(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utilisateur INTEGER NOT NULL, activite TEXT NOT NULL, texte TEXT NOT NULL, cree DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS strava(utilisateur INTEGER PRIMARY KEY, athlete TEXT, nom TEXT, acces TEXT NOT NULL,
  rafraichissement TEXT NOT NULL, expire DOUBLE PRECISION NOT NULL, portee TEXT);
CREATE TABLE IF NOT EXISTS etats_oauth(etat TEXT PRIMARY KEY, utilisateur INTEGER NOT NULL, retour TEXT,
  expire DOUBLE PRECISION NOT NULL);
"""

_reserve = None


def url():
    if config.DATABASE_URL:
        return config.DATABASE_URL
    try:
        import pgserver
    except ImportError:
        raise RuntimeError("DATABASE_URL manquant (adresse PostgreSQL). En développement : pip install pgserver")
    return pgserver.get_server(os.path.join(config.DONNEES, "postgres"), cleanup_mode=None).get_uri()


def reserve():
    """Connexions réutilisées : en ouvrir une par requête coûterait un aller-retour TLS vers la base distante.
    Autocommit : chaque écriture est validée tout de suite (une transaction explicite quand il faut du tout ou rien).
    Pas de requêtes préparées : elles cassent derrière les poolers de Neon et Supabase (mode transaction)."""
    global _reserve
    if _reserve is None:
        _reserve = ConnectionPool(url(), min_size=1, max_size=int(os.environ.get("LOOPY_CONNEXIONS", "10")),
                                  kwargs={"autocommit": True, "row_factory": dict_row,
                                          "prepare_threshold": None}, open=True)
    return _reserve


def fermer():
    global _reserve
    if _reserve is not None:
        _reserve.close()
        _reserve = None


def initialiser():
    with reserve().connection() as con:
        con.execute(SCHEMA)
